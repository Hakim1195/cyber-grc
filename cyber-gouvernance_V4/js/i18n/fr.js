//    sous le préfixe `valeur.` — §37.3, elles se traduisent à l'AFFICHAGE seul,
//    la valeur écrite ne bouge jamais et reste contrainte par les `check` ;
//  · les **catalogues métier** (1 500 textes de référentiels) sont le lot L11 ;

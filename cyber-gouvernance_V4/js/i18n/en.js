// ── Trois décisions de traduction, écrites parce qu'elles se rediscuteront ──
//
//  1. **Les noms de normes ne se traduisent pas.** « ISO 27001 » se dit
//     ISO 27001 partout, et « EBIOS », « ANSSI », « CNIL », « NIS2 », « DORA »,
//     « RGPD/GDPR » sont des noms propres. Seul `RGPD` devient `GDPR`, parce
//     que c'est le nom officiel du même texte en anglais — pas une traduction.
//  2. **Le vocabulaire métier suit l'usage anglophone de la profession**, pas le
//     mot à mot : *donneur d'ordre* → *client organisation*, *actif* → *asset*,
//     *exigence* → *requirement*, *mesure de sécurité* → *security control*,
//     *filiale* → *subsidiary*, *échéancier* → *deadlines*, *fiche* → *record*.
//  3. **Les libellés anglais sont plus courts** — souvent d'un tiers. Là où la
//     mise en page est contrainte (entrées de menu, en-têtes de colonne, tuiles
//     du tableau de bord), c'est sans risque : le texte rétrécit. Le sens
//     inverse — l'espagnol, plus long — est le cas à surveiller au lot suivant,
//     et c'est pourquoi aucun libellé n'est calibré au caractère près ici.
//
